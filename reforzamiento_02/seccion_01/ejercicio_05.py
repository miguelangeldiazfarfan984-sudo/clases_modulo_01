# Reforzamiento 02 - Ejercicio 05: Potencias y operaciones combinadas

# 1. Número entero positivo
numero = 4

# 2. Número elevado a la sexta potencia
potencia = numero ** 6

# 3. Número multiplicado por 2
multiplicacion = numero * 2

# 4. Restar la multiplicación a la potencia
resta = potencia - multiplicacion

# 5. Residuo de dividir el resultado entre 5
residuo = resta % 5

# 6. Mostrar resultados
print(f"Número inicial: {numero}")
print(f"Potencia elevada a 6: {potencia}")
print(f"Número multiplicado por 2: {multiplicacion}")
print(f"Resultado de la resta: {resta}")
print(f"Residuo de dividir entre 5: {residuo}")
